export const messages = { "zh-CN": zh, en }

export function createTranslator(locale: Locale) {
  return (key: MessageKey, values: MessageValues = {}) => {
    const message: Message = messages[locale][key]
    const template = typeof message === "string" ? message : Number(values.count) === 1 ? message.one : message.other
    return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder))
  }
}

// Catalog services keep their existing result contract; translate their public notices at the UI boundary.
const catalogKeys: MessageKey[] = ["catalog.audioError", "catalog.chapterFallback", "catalog.readError", "catalog.partial", "catalog.fallback", "catalog.error"]
export function getCatalogMessageKey(message: string): MessageKey {
  return catalogKeys.find((key) => zh[key] === message) ?? "catalog.error"
}
